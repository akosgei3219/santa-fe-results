"""Emit the top-10 finishers for a year as a plain, crawlable HTML block.

The post-race runbook task: mirror the top ten as static text on the
Results & Photos page so the results rank for our domain. Run it from any
machine that can reach RunSignup, then paste the output into a WordPress
Custom HTML block:

    python top10_html.py --year 2026            # block to stdout
    python top10_html.py --year 2026 -o top10.html

The block is intentionally script-free and inline-styled to survive any
page it lands on.
"""

import argparse
import html
import sys

import results


def render_top10(year: int, rows: list[dict]) -> str:
    """Render finisher rows as a static HTML block. Rows come from
    results.top_results (place, name, finish_time, pace_per_mile, gender)."""
    items = []
    for r in rows:
        name = html.escape(str(r.get("name", "")))
        time = html.escape(str(r.get("finish_time", "")))
        pace = html.escape(str(r.get("pace_per_mile", "")))
        gender = html.escape(str(r.get("gender", "") or ""))
        tail = f" ({gender})" if gender else ""
        items.append(
            f'    <li><strong>{name}</strong>{tail} &mdash; {time}'
            f'<span style="color:#A3A3A3"> &middot; {pace}/mi</span></li>'
        )
    joined = "\n".join(items)
    return f"""<!-- Top-10 mirror, generated by top10_html.py — plain text for search engines -->
<section style="background:#121212;border:1px solid #1E1E1E;border-radius:16px;padding:24px;color:#fff;font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,Helvetica,Arial,sans-serif;">
  <h3 style="margin:0 0 4px;color:#FFB800;">{year} Santa Fe International Half Marathon &mdash; Top 10 Finishers</h3>
  <p style="margin:0 0 14px;color:#A3A3A3;font-size:.9rem;">Official chip times. Full results on
    <a href="https://runsignup.com/Race/Results/{results.DEFAULT_RACE_ID}" style="color:#FFB800;">RunSignup</a>.</p>
  <ol style="margin:0;padding-left:22px;line-height:1.9;">
{joined}
  </ol>
</section>"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--year", type=int, required=True,
                        choices=sorted(results.HALF_MARATHON_EVENTS),
                        help="race edition to mirror")
    parser.add_argument("-o", "--out", help="write the block here instead of stdout")
    args = parser.parse_args(argv)

    try:
        rows = results.top_results(results.HALF_MARATHON_EVENTS[args.year], 10)
    except results.ResultsError as e:
        print(f"could not fetch results: {e}", file=sys.stderr)
        return 1
    if not rows:
        print(f"no results posted for {args.year}", file=sys.stderr)
        return 1

    block = render_top10(args.year, rows)
    if args.out:
        with open(args.out, "w", encoding="utf-8") as f:
            f.write(block + "\n")
        print(f"wrote {args.out} ({len(rows)} finishers)", file=sys.stderr)
    else:
        print(block)
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
